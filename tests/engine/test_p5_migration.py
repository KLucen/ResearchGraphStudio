def snapshot(database, tables=None):
    with sqlite3.connect(database) as db:
        tables = tables or [
            name
            for (name,) in db.execute(
                "SELECT name FROM sqlite_master WHERE type='table' AND name!='alembic_version'"
            )
        ]
        return {
            table: (
                db.execute(f'PRAGMA table_info("{table}")').fetchall(),
                sorted(db.execute(f'SELECT * FROM "{table}"').fetchall(), key=repr),
            )
            for table in tables
        }


def old_database(tmp_path):
    """Create genuine 0014 schema, then fill its tables with validated synthetic P4 records.

    The current P4 API creates the fixture in a separate donor database so all answer/raw/save
    lineage is valid. Only columns/tables actually present in the 0014 schema are transferred;
    no P5 tables, migrations, user database, model endpoint or OS credential is involved.
    FTS shadow rows are generated by inserting through the corresponding virtual table.
    """
    donor = tmp_path / "donor"
    with client(donor) as api:
        engine = seed(api)
        prepared, answer, provider = completed(api, engine, "p4-before-p5")
        saved_response = save(api, save_command(prepared, answer["answer"]))
        assert saved_response.status_code == 200, saved_response.text
        saved = saved_response.json()
        changed = metadata(
            api,
            saved["saved_id"],
            "annotation",
            0,
            annotation="Synthetic personal annotation retained independently.",
        )
        assert changed.status_code == 200, changed.text
        assert provider.calls == 1  # Explicit in-process test provider; zero external calls.
        with Session(engine) as session, session.begin():
            session.add(
                Job(
                    id="legacy-failed-job",
                    kind="knowledge_extract",
                    project_id="project",
                    status="failed",
                    stage="extracting",
                    payload={"legacy_signature": "unchanged"},
                    attempt=1,
                    error="Historical synthetic failure.",
                    result={},
                    created_at=now(),
                    updated_at=now(),
                )
            )
            session.flush()
            session.add(
                ModelRun(
                    id="legacy-failed-run",
                    job_id="legacy-failed-job",
                    document_version_id="version",
                    provider="synthetic-no-network",
                    model="fixture",
                    prompt_name="P02_historical",
                    prompt_hash="b" * 64,
                    schema_version="reading-1.0",
                    input_hash="c" * 64,
                    parameters={"historical_signature": "preserved"},
                    status="validation_failed",
                    raw_output='{"historical_raw":"原响应保持","unknown_field":true}',
                    error="Historical schema failure.",
                    created_at=now(),
                    finished_at=now(),
                )
            )

    data = tmp_path / "upgrade"
    engine = make_engine(data)
    config = Config()
    config.set_main_option(
        "script_location", str(Path("services/engine/researchgraph/migrations").resolve())
    )
    with engine.begin() as connection:
        config.attributes["connection"] = connection
        command.upgrade(config, "0014")
    engine.dispose()
    database = data / "researchgraph.sqlite3"
    with (
        sqlite3.connect(donor / "researchgraph.sqlite3") as source,
        sqlite3.connect(database) as db,
    ):
        # Direct SQLite fixture copying starts with FK enforcement off, then verifies the complete
        # copied relationship graph. Every production connection continues to enforce foreign keys.
        tables = [
            (name, kind)
            for _, name, kind, *_ in db.execute("PRAGMA table_list")
            if name not in {"alembic_version", "sqlite_schema", "sqlite_temp_schema"}
            and kind in {"table", "virtual"}
        ]
        for table, _ in tables:
            columns = [r[1] for r in db.execute(f'PRAGMA table_info("{table}")')]
            quoted = ",".join(f'"{column}"' for column in columns)
            values = source.execute(f'SELECT {quoted} FROM "{table}"').fetchall()
            db.execute(f'DELETE FROM "{table}"')
            if values:
                placeholders = ",".join("?" for _ in columns)
                db.executemany(f'INSERT INTO "{table}" ({quoted}) VALUES ({placeholders})', values)
        assert db.execute("PRAGMA foreign_key_check").fetchall() == []
        assert db.execute("PRAGMA integrity_check").fetchone() == ("ok",)
        assert db.execute("SELECT version_num FROM alembic_version").fetchone() == ("0014",)
    before = snapshot(database)
    for table in (
        "query_runs",
        "query_model_runs",
        "query_answer_versions",
        "query_documents",
        "query_document_versions",
        "query_passages",
        "query_saved_knowledge",
        "query_saved_preferences",
        "model_runs",
        "jobs",
    ):
        assert before[table][1], table
    return data, before, prepared["query_id"], saved["saved_id"], changed.json()


def test_populated_0014_upgrade_preserves_every_old_column_row_raw_and_exact_backup(tmp_path):
    data, before, _, _, _ = old_database(tmp_path)
    database = data / "researchgraph.sqlite3"
    engine = make_engine(data)
    migrate(engine, data)
    assert snapshot(database, before) == before
    with sqlite3.connect(database) as db:
        assert db.execute("SELECT version_num FROM alembic_version").fetchone() == (SCHEMA_HEAD,)
        assert SCHEMA_HEAD == "0020"
        assert db.execute("PRAGMA integrity_check").fetchone() == ("ok",)
        assert db.execute("PRAGMA foreign_key_check").fetchall() == []
        for table in (
            "lint_runs",
            "wiki_pages",
            "wiki_publications",
            "p5_workflows",
            "p5_model_runs",
        ):
            assert db.execute(f'SELECT count(*) FROM "{table}"').fetchone() == (0,)
    backups = list((data / "backups").glob("*.sqlite3"))
    assert len(backups) == 1
    with sqlite3.connect(backups[0]) as db:
        assert db.execute("SELECT version_num FROM alembic_version").fetchone() == ("0014",)
        assert db.execute("PRAGMA integrity_check").fetchone() == ("ok",)
        assert db.execute("PRAGMA foreign_key_check").fetchall() == []
    assert snapshot(backups[0]) == before
    all_rows = snapshot(database)
    migrate(engine, data)
    assert snapshot(database) == all_rows
    assert list((data / "backups").glob("*.sqlite3")) == backups
    engine.dispose()


def test_full_worker_restart_preserves_interrupted_p5_ledger_without_dispatch(
    tmp_path, monkeypatch
):
    data, before, query_id, saved_id, saved_metadata = old_database(tmp_path)
    database = data / "researchgraph.sqlite3"
    sends = []

    def forbidden_provider(*args, **kwargs):
        sends.append("provider")
        raise AssertionError("Restart must not load credentials or dispatch a model")

    async def forbidden_network(*args, **kwargs):
        sends.append("network")
        raise AssertionError("Restart must not send a model request")

    monkeypatch.setattr("researchgraph.p5_execution.from_snapshot", forbidden_provider)
    monkeypatch.setattr("researchgraph.query_answers.from_snapshot", forbidden_provider)
    monkeypatch.setattr("httpx.AsyncClient.send", forbidden_network)

    with client(data) as api:
        assert api.get("/api/v1/health").json()["schema_version"] == SCHEMA_HEAD
        assert snapshot(database, before) == before
        prepared = api.post(
            "/api/v1/projects/project/workflows/prepare",
            json={
                "kind": "wiki_synthesis",
                "query": {
                    "project_id": "project",
                    "question": "整理方法及适用条件",
                    "purpose": "model",
                },
            },
            headers={"Idempotency-Key": "restart-workflow-prepare"},
        )
        assert prepared.status_code == 200, prepared.text
        workflow_id = prepared.json()["id"]
        with Session(api.app.state.engine) as session, session.begin():
            workflow = session.get(P5Workflow, workflow_id)
            job = enqueue(session, workflow, "restart-workflow-dispatch", continue_requested=False)
            job_id = job.id
            # Emulate a durable, already-sent slot at the exact I/O boundary. No real send occurs.
            workflow.status = "running"
            session.add(
                P5ModelRun(
                    id="interrupted-p5-slot",
                    workflow_id=workflow_id,
                    job_id=job_id,
                    sequence=1,
                    prompt_name="P10_reading_synthesis_v1",
                    prompt_hash=workflow.snapshot["prompt_hash"],
                    input_hash=workflow.snapshot["wire_hash"],
                    parameters={
                        "dispatch_policy": "persist-before-io-no-resend-1",
                        "raw_complete": False,
                        "workflow_hash": workflow.input_hash,
                        "usage": {},
                        "cost_known": False,
                    },
                    status="running",
                    raw_output='{"partial":"原响应未完成',
                    error=None,
                    created_at=now(),
                    finished_at=None,
                )
            )

    # Set the crash state after the normal fixture closes, so startup itself must recover it.
    engine = make_engine(data)
    with Session(engine) as session, session.begin():
        session.get(Job, job_id).status = "running"
        ledger = session.get(P5ModelRun, "interrupted-p5-slot")
        original_ledger = {
            name: getattr(ledger, name)
            for name in (
                "id",
                "workflow_id",
                "job_id",
                "sequence",
                "prompt_name",
                "prompt_hash",
                "input_hash",
                "parameters",
                "raw_output",
                "created_at",
            )
        }
    engine.dispose()

    for _ in range(2):
        with client(data, worker=True) as api:
            assert api.get("/api/v1/health").status_code == 200
            answer = api.get(PREFIX + f"/runs/{query_id}/answer")
            assert answer.status_code == 200 and answer.json()["status"] == "succeeded", answer.text
            saved = api.get(PREFIX + f"/saved/{saved_id}")
            assert saved.status_code == 200, saved.text
            assert saved.json() == saved_metadata
            workflow = api.get(f"/api/v1/projects/project/workflows/{workflow_id}")
            assert workflow.status_code == 200, workflow.text
            assert workflow.json()["status"] == "interrupted"
            assert workflow.json()["request_count"] == 1
            with Session(api.app.state.engine) as session:
                assert session.get(Job, job_id).status == "interrupted"
                ledger = session.get(P5ModelRun, "interrupted-p5-slot")
                assert ledger.status == "interrupted"
                assert {name: getattr(ledger, name) for name in original_ledger} == original_ledger
                assert len(list(session.scalars(select(P5ModelRun)))) == 1
            # The only old-table additions are the explicit P5 job/operation/audit records.
            append_only = {"jobs", "query_operations", "knowledge_events"}
            immutable = {
                table: value
                for table, value in before.items()
                if table not in append_only | {"sqlite_sequence"}
            }
            assert snapshot(database, immutable) == immutable
            for table in append_only:
                current_columns, current_rows = snapshot(database, [table])[table]
                old_columns, old_rows = before[table]
                assert current_columns == old_columns
                assert all(row in current_rows for row in old_rows)
            assert sends == []
    assert len(list((data / "backups").glob("*.sqlite3"))) == 1
